const int32_t COMPCPlusPlusPanelAPIVersion = 1 | (OP_CommonAPIVersion << 16);

class COMP_PanelPluginInfo
{
public:
	// Returns false if the API version is not supported
	[[nodiscard]]
	int32_t
	getAPIVersion() const
	{
		return apiVersion;
	}

	// Should be called with a value of DATCPlusPlusAPIVersion
	[[nodiscard]]
	bool
	setAPIVersion(int32_t version)
	{
		apiVersion = version;

		if (!isAPIVersionSupported(version))
			return false;

		return true;
	}
	[[nodiscard]]
	bool
	isAPIVersionSupported(int32_t version)
	{
		return checkAPIVersionSupported(version, MinAPIVersion, MaxAPIVersion);
	}

	COMP_PanelRenderMode	renderMode = COMP_PanelRenderMode::VulkanTexture;

	// Information used to describe this plugin as a custom OP.
	OP_CustomOPInfo	customOPInfo;

	int32_t			reserved[100] = {};

	static constexpr bool checkPrivateOffsets();

private:
	// Set it by calling setAPIVersion()
	int32_t			apiVersion = 0;

	// Will be set by the caller of FillCOMPPluginInfo()
	const int32_t	MinAPIVersion = 0;
	const int32_t	MaxAPIVersion = 0;
	friend class ::OBJ_CPlusPlusPanel;
};

constexpr bool
COMP_PanelPluginInfo::checkPrivateOffsets()
{
	return offsetof(COMP_PanelPluginInfo, apiVersion) == 0 &&
		offsetof(COMP_PanelPluginInfo, MinAPIVersion) == 408 + sizeof(customOPInfo) + 18 * 4 &&
		offsetof(COMP_PanelPluginInfo, MaxAPIVersion) == 408 + sizeof(customOPInfo) + 18 * 4 + 4;
}

